def clean(root):
    root = Path(root)
    removed = 0
    for module_dir in MODULE_JAVA_ROOT.values():
        base = root / module_dir
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if not path.is_file():
                continue
            if path.suffix not in (".java", ".xml"):
                continue
            try:
                text = path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            if MARKER in text:
                path.unlink()
                removed += 1
    # 删除空目录
    for module_dir in MODULE_JAVA_ROOT.values():
        base = root / module_dir
        if not base.exists():
            continue
        for path in sorted(base.rglob("*"), key=lambda p: len(str(p)), reverse=True):
            if path.is_dir():
                try:
                    path.rmdir()
                except OSError:
                    pass
    return removed


